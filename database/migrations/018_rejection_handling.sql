CREATE TABLE IF NOT EXISTS rejection_case (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    organization_id BIGINT NOT NULL,
    dispatch_id BIGINT NOT NULL,
    packing_id BIGINT NOT NULL,
    item_id BIGINT NOT NULL,
    source_json MEDIUMTEXT NOT NULL,
    source_hash VARCHAR(64) NOT NULL,
    initial_hash VARCHAR(64) NOT NULL,
    state_hash VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'OPEN',
    revision INT NOT NULL DEFAULT 0,
    package_unit VARCHAR(32) NOT NULL,
    net_weight_kg DECIMAL(15,3) NOT NULL,
    last_physical_at DATETIME(6) NOT NULL,
    warehouse_id BIGINT,
    quarantine_location VARCHAR(256),
    reason VARCHAR(500) NOT NULL,
    recorded_by BIGINT NOT NULL,
    recorded_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    request_key VARCHAR(36) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    UNIQUE KEY uk_rejection_item (item_id),
    UNIQUE KEY uk_rejection_request (request_key),
    KEY idx_rejection_org_state (organization_id,status,id),
    KEY idx_rejection_warehouse (warehouse_id,status,id),
    CONSTRAINT ck_rejection_state CHECK (status IN ('OPEN','RETURNING','QUARANTINED','DISPOSED')),
    CONSTRAINT fk_rejection_item FOREIGN KEY (item_id) REFERENCES item_dispatch_link(item_id),
    CONSTRAINT fk_rejection_warehouse FOREIGN KEY (warehouse_id) REFERENCES inventory_warehouse(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS rejection_event (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    case_id BIGINT NOT NULL,
    revision INT NOT NULL,
    kind VARCHAR(32) NOT NULL,
    occurred_at DATETIME(6) NOT NULL,
    warehouse_id BIGINT,
    quarantine_location VARCHAR(256),
    performer_name VARCHAR(128) NOT NULL,
    note VARCHAR(1000) NOT NULL,
    reference VARCHAR(128),
    target_revision INT,
    previous_hash VARCHAR(64) NOT NULL,
    event_hash VARCHAR(64) NOT NULL,
    payload_json MEDIUMTEXT NOT NULL,
    recorded_by BIGINT NOT NULL,
    recorded_at DATETIME(6) NOT NULL,
    request_key VARCHAR(36) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    UNIQUE KEY uk_rejection_revision (case_id,revision),
    UNIQUE KEY uk_rejection_event_request (request_key),
    CONSTRAINT ck_rejection_revision CHECK (revision BETWEEN 1 AND 100),
    CONSTRAINT ck_rejection_event_kind CHECK (kind IN ('RETURN_DISPATCH','QUARANTINE_RECEIVE','DISPOSE','ANNOTATION')),
    CONSTRAINT fk_rejection_event_case FOREIGN KEY (case_id) REFERENCES rejection_case(id),
    CONSTRAINT fk_rejection_event_warehouse FOREIGN KEY (warehouse_id) REFERENCES inventory_warehouse(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
