CREATE TABLE IF NOT EXISTS source_quality_report (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    organization_id BIGINT NOT NULL,
    scope_type VARCHAR(16) NOT NULL,
    harvest_id BIGINT NOT NULL,
    packing_id BIGINT,
    report_no VARCHAR(64) NOT NULL,
    agency_name VARCHAR(128) NOT NULL,
    sampled_on DATE NOT NULL,
    checked_on DATE NOT NULL,
    declared_result VARCHAR(32) NOT NULL,
    file_name VARCHAR(128) NOT NULL,
    file_type VARCHAR(32) NOT NULL,
    file_size INT NOT NULL,
    file_sha256 VARCHAR(64) NOT NULL,
    manifest_json MEDIUMTEXT NOT NULL,
    manifest_hash VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    attachment_public BOOLEAN NOT NULL DEFAULT FALSE,
    recorded_by BIGINT NOT NULL,
    recorder_name VARCHAR(128) NOT NULL,
    recorded_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    published_by BIGINT,
    publisher_name VARCHAR(128),
    published_at DATETIME(6),
    withdrawn_by BIGINT,
    withdrawn_at DATETIME(6),
    withdraw_reason VARCHAR(500),
    request_key VARCHAR(36) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    UNIQUE KEY uk_source_quality_request (request_key),
    UNIQUE KEY uk_source_quality_manifest (organization_id,manifest_hash),
    INDEX idx_source_quality_number (organization_id,report_no),
    INDEX idx_quality_harvest (harvest_id,id),
    INDEX idx_quality_packing (packing_id,id),
    CONSTRAINT ck_quality_scope CHECK ((scope_type='HARVEST' AND packing_id IS NULL) OR (scope_type='PACKING' AND packing_id IS NOT NULL)),
    CONSTRAINT ck_quality_result CHECK (declared_result IN ('PASS','FAIL','INCONCLUSIVE')),
    CONSTRAINT ck_quality_status CHECK (status IN ('DRAFT','PUBLISHED','WITHDRAWN')),
    CONSTRAINT ck_quality_size CHECK (file_size BETWEEN 1 AND 5242880),
    CONSTRAINT ck_quality_manifest CHECK (JSON_VALID(manifest_json)),
    CONSTRAINT fk_quality_source_harvest FOREIGN KEY (harvest_id) REFERENCES harvest_lot(id),
    CONSTRAINT fk_quality_source_packing FOREIGN KEY (packing_id) REFERENCES packing_lot(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS source_quality_attachment (
    report_id BIGINT PRIMARY KEY,
    content MEDIUMBLOB NOT NULL,
    CONSTRAINT fk_quality_attachment_report FOREIGN KEY (report_id) REFERENCES source_quality_report(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
